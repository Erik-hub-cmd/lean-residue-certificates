import sys, re, math
name, title, dmax = sys.argv[1], sys.argv[2], int(sys.argv[3])
s = open('/root/lr/LeanResidy/Case346.lean').read()
s = s.replace('Data346', f'Data{name}').replace('namespace C346', f'namespace C{name}').replace('end C346', f'end C{name}')
s = s.replace('# 3⁴.6 med vikt 4 (artikel 2): maskinkontrollerade identiteter', f'# {title}: maskinkontrollerade identiteter')
s = s.replace('för\n3⁴.6 (vikt 4)', f'för\n{title}')
s = s.replace('def dmax : ℕ := 32', f'def dmax : ℕ := {dmax}')
ch = math.ceil((dmax + 1) / 3)
s = s.replace('List.range 11).all fun j => pointOK ((j : ℚ) + 2)', f'List.range {ch}).all fun j => pointOK ((j : ℚ) + 2)')
