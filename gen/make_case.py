s = s.replace('List.range 11).all fun j => pointOK ((j : ℚ) + 24)', f'List.range {ch}).all fun j => pointOK ((j : ℚ) + {2+2*ch})')
s = s.replace('rcases Nat.lt_or_ge j 11 with h | h', f'rcases Nat.lt_or_ge j {ch} with h | h')
s = s.replace('rcases Nat.lt_or_ge j 22 with', f'rcases Nat.lt_or_ge j {2*ch} with')
s = s.replace('h1 (j - 11)', f'h1 (j - {ch})').replace('((j - 11 : ℕ) : ℚ) + 13', f'((j - {ch} : ℕ) : ℚ) + {2+ch}')
s = s.replace('h2 (j - 22)', f'h2 (j - {2*ch})').replace('((j - 22 : ℕ) : ℚ) + 24', f'((j - {2*ch} : ℕ) : ℚ) + {2+2*ch}')
# kroppen i docstring
s = s.replace('Kropp `K = ℚ(r, s)`, `r² = −3`, `s² = −35`.', 'Kropp `K = ℚ(r, s)`, `r² = KA`, `s² = KB` (se datafilen).')
s = s.replace('(`x₁ = v₁ v₂⁻²`, `x₂ = v₂`)', '(`T` i datafilen)')
open(f'/root/lr/LeanResidy/Case{name}.lean', 'w').write(s)
